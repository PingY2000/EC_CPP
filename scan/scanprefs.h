/*
 * scan/scanprefs.h —— 参数的**记忆** (exe 旁边那个 scan.ini)
 *
 * 记住三件事, 别的都不记:
 *
 *   · **扫描参数** (区域 / 分辨率 / 1 单位 = ? 脉冲 / 速度 / 停留 / 稳定 / 采样 / 方向)
 *   · **上次用的网卡** —— 这是最要紧的一条: 一台上位机常有好几块网卡, 而每次开程序
 *     都要在十条 `\Device\NPF_{GUID}` 里认出上次那条, 是纯粹的浪费 (而且**认错一条
 *     就等于连错一块卡**)。
 *   · 手动速度 (点画布走点用的那个, pul/s)
 *
 * ── 为什么不记别的 (每一条都是想过之后决定不记的) ──────────────────────────
 *
 *   · **CSV 输出路径**: 文件名带时间戳, 记住它等于把上趟的数据盖上, 或者把新数据
 *     默认写到别的地方去 —— 而 `scan_out/` (工作目录下) 正是 .gitignore 兜住的那个。
 *   · **色标上下限**: 它是**这一张图**的显示参数。把上趟锁定的小范围套到新数据上,
 *     新图会看着是空的 —— 那是最坏的一类"看着坏了、其实没坏"。每次都从 0..1 起。
 *   · **功率计那几项**: 三个模拟源是穷举流程用的, 记它们没有意义。真机 (PD300R +
 *     Juno+, 见 ophirmeter.h) 那边**更加不能记**: 波长/量程/模式/探头工况都是**设备
 *     自己的状态**, 由设备说了算 —— 拿本程序上次的选择去盖, 等于让一个 ini 文件去
 *     猜一块表头的当前配置。打开时读设备, 要改在界面上点。
 *   · **「让 60FDh 进 TxPDO」**: 它一勾, 连接时会往驱动器的 PDO 映射里写字节
 *     (仅 RAM)。那种事每次都要人**当面**决定, 不做持久化 —— 与界面里"没有持久勾选"
 *     的先例一致。
 *
 * ── 为什么单独一个文件 ────────────────────────────────────────────────────
 *
 * **只链 Qt6::Core** (QSettings 在 Core 里), 所以 `scan_selftest` 能把它真跑一遍:
 * 存进去、读回来、逐项比。这一层最容易悄悄错 —— 键名写错一个字母不报错,
 * 只是让人下次打开发现"参数没记住", 而那要等到明年才发现。
 */
#pragma once

#include <QString>

#include "scanplan.h"

namespace scan {

struct Prefs
{
   Params  params;                  /* 缺省就是 scanplan.h 里那份缺省 */
   QString nic;                     /* 上次连接用的网卡 (Npcap 名), 空 = 没记过 */
   int     manual_speed = -1;       /* 手动速度 pul/s; **-1 = 没记过** (窗口用 HMI_VEL_DEF) */
};

/* ini 放哪儿: **exe 旁边** (bin/scan.ini)。跟着程序走, 一眼能找到, 想清零就删了它 */
QString prefsPath();

/*
 * 读回来。**文件不存在 / 某项缺失都不算错** —— 缺的项保持上面那份缺省,
 * 于是"第一次运行"和"读一个被删了一半的 ini"是同一条路径, 不必各写一遍。
 */
Prefs prefsLoad(const QString &path);

/*
 * 写回去 (整个文件重写)。**写不进去不算错**: 目录只读、盘满、文件被别的程序占着,
 * 都只是这一次没记住 —— 为它弹一个框、或者拦下一次连接, 都不值得。
 */
void prefsSave(const QString &path, const Prefs &p);

/*
 * 把"现在这份参数"并进一份已经读回来的记忆里。
 *
 * **过不了 validate() 的当前参数不覆盖旧的。** 否则一次手滑 (分辨率少打一位) 关窗之后,
 * 下次打开就是一个"网格没建、开始按不动"的局面 —— 而那份参数本来也不能扫。
 * 于是宁可保留上一次**能用**的那份: 记忆的用处是省下重填的功夫, 不是如实记录每一次手滑。
 *
 * 量程 (range_pul) 一律归零 —— 它是从区域算出来的 (autoRangePul), 记一份下来就是第二份真相。
 */
void prefsMergeParams(Prefs *store, const Params &cur);

}   /* namespace scan */
